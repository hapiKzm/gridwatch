CREATE TABLE reading (
                                id uuid NOT NULL PRIMARY KEY,
                                created_at timestamp(6) with time zone NOT NULL,
                                measured_at timestamp(6) with time zone NOT NULL,
                                sensor_type character varying(255) NOT NULL,
                                substation_id character varying(255) NOT NULL,
                                updated_at timestamp(6) with time zone NOT NULL,
                                value double precision NOT NULL,
                                CONSTRAINT reading_sensor_type_check CHECK (((sensor_type)::text = ANY ((ARRAY['TEMPERATURE'::character varying, 'LOAD'::character varying])::text[])))
);


CREATE TABLE work_order (
                                   id bigint generated by default as identity NOT NULL PRIMARY KEY,
                                   created_at timestamp(6) with time zone NOT NULL,
                                   reason character varying(255) NOT NULL,
                                   substation_id character varying(255) NOT NULL,
                                   updated_at timestamp(6) with time zone NOT NULL,
                                   work_order_status character varying(255) NOT NULL,
                                   CONSTRAINT work_order_work_order_status_check CHECK (((work_order_status)::text = ANY ((ARRAY['OPEN'::character varying, 'CLOSED'::character varying])::text[])))
);
